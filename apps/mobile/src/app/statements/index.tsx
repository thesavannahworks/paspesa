import { buildStatement, formatStatementAmount, toLocalParts } from '@paspesa/core';
import { router } from 'expo-router';
import { useMemo, useState } from 'react';
import { Pressable, ScrollView, StyleSheet, View } from 'react-native';
import { Avatar, Field, Inert, Screen, ScreenHeader, T } from '@/components/ui';
import { ExportIcon, SearchIcon, SpendIcon, VerifiedIcon } from '@/icons';
import { useAppState } from '@/services/AppState';
import { useTheme } from '@/theme/ThemeProvider';

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/** M-PESA Statements (reference: 09-statements). Built from the transaction ledger only. */
export default function StatementsScreen() {
  const { colors } = useTheme();
  const { transactions, deps } = useAppState();
  const offset = deps.config.utcOffsetMinutes;
  const [search, setSearch] = useState('');

  const months = useMemo(() => {
    const keys = new Set<string>();
    for (const t of transactions) {
      const p = toLocalParts(t.completedAt, offset);
      keys.add(`${p.year}-${String(p.month).padStart(2, '0')}`);
    }
    return [...keys].sort().reverse();
  }, [transactions, offset]);
  const [month, setMonth] = useState<string | null>(null);
  const activeMonth = month ?? months[0] ?? null;

  const statement = useMemo(() => {
    const range = activeMonth ? { fromDate: `${activeMonth}-01`, toDate: `${activeMonth}-31` } : {};
    return buildStatement(transactions, { utcOffsetMinutes: offset, search: search || undefined, ...range });
  }, [transactions, offset, search, activeMonth]);

  return (
    <Screen>
      <ScreenHeader title="M-PESA Statements" />
      <T variant="label" color={colors.textSecondary} style={{ marginTop: 18 }}>Statement Options</T>
      <View style={styles.options}>
        <Option icon={<ExportIcon size={30} />} label={'Export\nStatements'} />
        <Option icon={<SpendIcon size={30} />} label={'View\nMy Spend'} />
        <Option icon={<VerifiedIcon size={30} />} label={'Statement\nVerification'} />
      </View>
      <Field value={search} onChangeText={setSearch} placeholder="Search" left={<SearchIcon size={26} />} focusedBorder={false} style={{ fontSize: 19 }} />
      <ScrollView horizontal showsHorizontalScrollIndicator={false} contentContainerStyle={{ gap: 10, marginTop: 18 }}>
        {months.map((m) => {
          const active = m === activeMonth;
          return (
            <Pressable key={m} onPress={() => setMonth(m)} accessibilityRole="button" accessibilityState={{ selected: active }}
              style={[styles.chip, { backgroundColor: active ? colors.green : colors.raised }]}>
              <T variant="body" color={active ? '#FFFFFF' : colors.text} style={{ fontSize: 18 }}>{MONTHS[Number(m.slice(5)) - 1]}</T>
            </Pressable>
          );
        })}
      </ScrollView>

      {statement.rowCount === 0 ? (
        <T variant="body" color={colors.textSecondary} center style={{ marginTop: 40 }}>{search ? 'No matching transactions.' : 'No transactions yet.'}</T>
      ) : null}

      {statement.groups.map((g) => (
        <View key={g.dateKey} style={{ marginTop: 26 }}>
          <T variant="bodyStrong" style={{ fontSize: 19, fontWeight: '600' }}>{g.heading}</T>
          {g.rows.map((r) => (
            <Pressable key={r.transactionId} accessibilityRole="button" onPress={() => router.push({ pathname: '/statements/[id]', params: { id: r.transactionId } })}
              style={({ pressed }) => [styles.row, pressed && { opacity: 0.7 }]}>
              <Avatar name={r.title || 'P'} size={56} fontSize={19} />
              <View style={{ flex: 1, marginLeft: 18 }}>
                <T variant="body" numberOfLines={1} style={{ fontSize: 19 }}>{r.title}</T>
                <T variant="body" color={colors.textSecondary} numberOfLines={1} style={{ fontSize: 17, marginTop: 6 }}>{r.subtitle}</T>
              </View>
              <View style={{ alignItems: 'flex-end' }}>
                <T variant="body" style={{ fontSize: 19 }}>{formatStatementAmount(r.signedAmount)}</T>
                <T variant="body" color={colors.textSecondary} style={{ fontSize: 17, marginTop: 6 }}>{r.time}</T>
              </View>
            </Pressable>
          ))}
        </View>
      ))}
      <T variant="caption" color={colors.textMuted} center style={{ marginTop: 30 }}>Simulated statement generated by Paspesa — not a Safaricom statement.</T>
    </Screen>
  );
}

function Option({ icon, label }: { icon: React.ReactNode; label: string }) {
  const { colors } = useTheme();
  return (
    <Inert style={[styles.option, { backgroundColor: colors.mode === 'dark' ? colors.surface : colors.screen, borderColor: colors.border }]}>
      {icon}
      <T variant="label" center style={{ marginTop: 10, lineHeight: 21 }}>{label}</T>
    </Inert>
  );
}

const styles = StyleSheet.create({
  options: { flexDirection: 'row', gap: 12, marginTop: 14 },
  option: { flex: 1, alignItems: 'center', borderRadius: 16, paddingVertical: 18, borderWidth: StyleSheet.hairlineWidth, elevation: 1 },
  chip: { paddingHorizontal: 26, paddingVertical: 12, borderRadius: 24 },
  row: { flexDirection: 'row', alignItems: 'center', marginTop: 22 },
});
