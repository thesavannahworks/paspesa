import { formatTime12, localDateKey, markAllMessagesRead, toLocalParts, type MessageRecord } from '@paspesa/core';
import { router } from 'expo-router';
import { useEffect, useMemo } from 'react';
import { ScrollView, StyleSheet, View } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { CircleButton, T } from '@/components/ui';
import { ChevronLeftIcon } from '@/icons';
import { useAppState } from '@/services/AppState';
import { useTheme } from '@/theme/ThemeProvider';

const DAYS = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

/**
 * Generated confirmation messages, oldest first like an SMS thread (reference: 08-messages).
 * Every message is linked to its committed transaction.
 */
export default function MessagesScreen() {
  const { colors } = useTheme();
  const { messages, deps, refresh } = useAppState();
  const offset = deps.config.utcOffsetMinutes;

  useEffect(() => {
    if (messages.some((m) => !m.readAt)) void markAllMessagesRead(deps).then(refresh);
  }, [messages, deps, refresh]);

  const groups = useMemo(() => {
    const sorted = [...messages].sort((a, b) => (a.createdAt < b.createdAt ? -1 : 1));
    const out: Array<{ key: string; heading: string; items: MessageRecord[] }> = [];
    for (const m of sorted) {
      const p = toLocalParts(m.createdAt, offset);
      const key = localDateKey(p);
      let g = out[out.length - 1];
      if (!g || g.key !== key) {
        const weekday = DAYS[new Date(Date.UTC(p.year, p.month - 1, p.day)).getUTCDay()];
        g = { key, heading: `${weekday}, ${p.day} ${MONTHS[p.month - 1]}`, items: [] };
        out.push(g);
      }
      g.items.push(m);
    }
    return out;
  }, [messages, offset]);

  return (
    <SafeAreaView style={{ flex: 1, backgroundColor: colors.mode === 'dark' ? '#000000' : colors.screen }} edges={['top', 'bottom']}>
      <View style={styles.header}>
        <CircleButton label="Back" onPress={() => router.back()}><ChevronLeftIcon color={colors.text} size={22} /></CircleButton>
        <View style={[styles.senderAvatar, { backgroundColor: colors.raised }]} />
        <T variant="title" style={{ fontSize: 26, fontWeight: '600' }}>M-PESA</T>
      </View>
      <T variant="caption" color={colors.textMuted} center style={{ marginBottom: 6 }}>Simulated messages generated by Paspesa</T>
      <ScrollView contentContainerStyle={{ padding: 16, paddingBottom: 40 }}>
        {groups.length === 0 ? (
          <T variant="body" color={colors.textSecondary} center style={{ marginTop: 60 }}>No messages yet.</T>
        ) : null}
        {groups.map((g) => (
          <View key={g.key}>
            <T variant="label" color={colors.textSecondary} center style={{ marginVertical: 16 }}>{g.heading}</T>
            {g.items.map((m) => (
              <View key={m.id} style={styles.row}>
                <View style={[styles.bubble, { backgroundColor: colors.mode === 'dark' ? '#3A3A3C' : '#ECECEE' }]}>
                  <T variant="body" style={{ fontSize: 17, lineHeight: 24 }}>{m.body}</T>
                </View>
                <T variant="caption" color={colors.textSecondary} style={{ alignSelf: 'flex-end', marginLeft: 8, marginBottom: 4 }}>
                  {formatTime12(toLocalParts(m.createdAt, offset)).replace(/ (AM|PM)$/, '')}
                </T>
              </View>
            ))}
          </View>
        ))}
      </ScrollView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  header: { flexDirection: 'row', alignItems: 'center', gap: 14, paddingHorizontal: 16, paddingVertical: 12 },
  senderAvatar: { width: 46, height: 46, borderRadius: 23 },
  row: { flexDirection: 'row', marginBottom: 12, paddingRight: 30 },
  bubble: { flexShrink: 1, borderRadius: 22, paddingHorizontal: 18, paddingVertical: 12 },
});
